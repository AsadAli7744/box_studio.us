function hydrate(item) {
  const structure = getProduct(item.structure);
  const category = shopCategories.find((entry) => entry.slug === item.category);
  return {
    ...structure,
    slug: item.slug,
    name: item.name,
    category: item.category,
    categoryLabel: category ? category.name : item.category,
    structureName: structure.name,
    structureSlug: structure.slug,
    short: item.short,
    description: item.description,
    meta: item.meta,
    images: [{ src: item.image, alt: item.alt }, ...(extraImages[item.slug] || [])],
    sections: [
      { heading: item.needHeading, body: item.fit },
      { heading: item.apartHeading, body: item.apart },
      { heading: 'What to send with the quote', body: item.measure },
    ],
    faqs: item.faqs,
    related: item.related,
    applications: item.uses,
  };
}

